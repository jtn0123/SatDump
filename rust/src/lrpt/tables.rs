//! The tables of the C++ decoder (`plugins/meteor_support/meteor/instruments/msumr/lrpt/tables.h`),
//! in the same order: the JPEG luminance quantisation table, the zig-zag order, and the DC and
//! AC Huffman codes. A code is its bits as a number (the first bit highest) and its length.
//! The Huffman lists were written out from tables.h by a script, entry for entry.

/// A DC code: `klen` bits of `code`, then a value of `len` bits
pub(super) struct Dc {
    pub code: u32,
    pub klen: usize,
    pub len: usize,
}

/// An AC code: `klen` bits of `code`, then a value of `clen` bits after `zlen` zeros
pub(super) struct Ac {
    pub code: u32,
    pub klen: usize,
    pub clen: usize,
    pub zlen: usize,
}

